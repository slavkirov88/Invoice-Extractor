export async function POST(request: NextRequest) {
  try {
    const apiKey = process.env.MISTRAL_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { message: "Чатът е временно недостъпен. Моля, опитайте по-късно." },
        { status: 200 }
      );
    }

    const { messages } = await request.json();

    if (!messages || !Array.isArray(messages)) {
      return NextResponse.json(
        { message: "Невалидна заявка." },
        { status: 400 }
      );
    }

    const client = new Mistral({ apiKey });

    const response = await client.chat.complete({
      model: "mistral-small-latest",
      messages: [
        { role: "system", content: SYSTEM_PROMPT },
        ...messages.slice(-10).map((m: { role: string; content: string }) => ({
          role: m.role as "user" | "assistant",
          content: m.content,
        })),
      ],
      maxTokens: 500,
      temperature: 0.5,
    });

    const assistantMessage =
      response.choices?.[0]?.message?.content || "Съжалявам, не можах да генерирам отговор.";

    return NextResponse.json({ message: assistantMessage });
  } catch (error) {
    console.error("Chat API error:", error);
    return NextResponse.json(
      {
        message:
          "Нещо се обърка. Опитайте пак след малко или ни пишете на support@travelinvoices.com.",
      },
      { status: 200 }
    );
  }
}
